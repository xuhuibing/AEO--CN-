#!/bin/bash
# AEO认证稽核系统 - 隧道启动脚本
# 将本地 AEO 服务器暴露到公网，供飞书智能体调用
# 使用方式:
#   ./tunnel.sh              (默认端口3080)
#   ./tunnel.sh 8080         (自定义服务器端口)

PORT=${1:-3080}
SUBDOMAIN="aeo-$(openssl rand -hex 4)"

echo ""
echo "  ┌─────────────────────────────────────────────────────────────┐"
echo "  │  AEO认证稽核系统 · 隧道 (Cloudflare Tunnel)                │"
echo "  ├─────────────────────────────────────────────────────────────┤"
echo "  │  请先确保 AEO 服务器已在本地运行: ./start.sh               │"
echo "  │  隧道将本地端口 $PORT 暴露到公网                             │"
echo "  │  生成的公网地址请在 30 秒后使用                             │"
echo "  ├─────────────────────────────────────────────────────────────┤"
echo "  │  Ctrl+C 停止隧道                                           │"
echo "  └─────────────────────────────────────────────────────────────┘"
echo ""

cloudflared tunnel --url "http://localhost:${PORT}"
